                <li>Buddhism, Humanities, and Social Sciences amid World Modern Society Life.</li>
                <li>Mindfulness and Applied Buddhism in Building Human Civilization and Humanity. </li>
                <li>Mindfulness in Education, Communication, and Economics in the World and Buddhist Society.</li>
                <li>Buddhayana Values: a return to core Buddhism in the life of multicultural and diverse modern society. </li>
                <li>The development of humanity within the framework of religious moderation by bringing Applied Buddhism and the Buddhayana Spirit Movement views and practices.</li>
                <li>Buddhayana Spirit Movements: A Legacy of 'Nusantara' Buddhism in Indonesia. </li>
              </ol>

              <b><p style="text-align: justify;" >The Implementation of Applied Buddhism and Buddhayana Spirit Movement in Buddhist Studies, Buddhism of Art, Buddhist Philosophy, and Buddhism Development nowadays</p></b>
              <ol>
                <li>View of the late most venerable Ashin Jinarakkhita' advocating and teaching on the Buddhayana spirit movement in the context of Indonesia's Buddhism development.</li>
                <li>The existence and propagation of Buddhist art in modern society. </li>
                <li>Borobudur temple is the legacy of Indonesian Buddhism and world Buddhist art heritage.</li>
                <li>The problem of radicalism and intolerance amid Buddhist schools diversity in the Buddhist community. </li>
                <li>Implementing mindfulness practice and Buddhist meditation according to Buddhist discourses in daily life.</li>
                <li>The Buddhist discourses on applied Buddhism and Buddhayana spirit movement. </li>
              </ol>

              <b><p>The scope of each sub-theme, as general, according to Applied Buddhism and Buddhayana Spirit Movement, can be related to:</p></b>
              <ol>
                <li>Buddhist in Education, Communication Science, and Economic</li>
                <li>Buddhism, Social Sciences, and Humanity </li>
                <li>Buddhism in Religious Studies and Moderation</li>
                <li>Buddhist Studies, Buddhist Meditation, Buddhism History, Buddhism Art & Philosophy </li>
                <li>Mindfulness in Multidisciplinary</li>
