                are divided into three groups according to the symposium theme, namely about Applied Buddhism and the Buddhayana Spirit Movement in all aspects of society life, as follows.
              </p>

              <p style="text-align: justify;" > <b> Influencing and Strengthening the Applied Buddhism and Buddhayana Spirit Movement toward society life relate to the aspects of Education, Economics, Politics, Religion, Social, Culture, and Humanity in modern society </b> </p>
